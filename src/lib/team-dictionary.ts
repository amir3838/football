export function normalizeTeamName(value: string) {
  return value.trim().toLowerCase().replace(/أ|إ|آ/g, 'ا').replace(/ى/g, 'ي').replace(/ة/g, 'ه').replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
}

export function findTeamInDictionary(query: string) {
  const normalized = normalizeTeamName(query);
  return teamDictionary.find(entry => normalizeTeamName(entry.english) === normalized || normalizeTeamName(entry.arabic) === normalized || entry.aliases.some(alias => normalizeTeamName(alias) === normalized));
}
